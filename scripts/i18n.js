function changeLanguageGRALAdib(lang) {
    if (!translations[lang]) {
        console.warn(`Idioma no soportado: ${lang}. Usando euskera por defecto.`);
        lang = 'eu';
    }

    document.documentElement.lang = lang;

    const t = translations[lang];

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (t[key]) {
            element.textContent = t[key];
        }
    });

    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (t[key]) {
            element.setAttribute('placeholder', t[key]);
        }
    });

    localStorage.setItem('lang', lang);
}

document.addEventListener('change', () => {
    const savedLang = localStorage.getItem('lang') || 'eu';
    changeLanguageGRALAdib(savedLang);
});

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('lang') || 'eu';
    changeLanguageGRALAdib(savedLang);
});

window.changeLanguageGRALAdib = changeLanguageGRALAdib;
